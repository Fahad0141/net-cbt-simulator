/** Default chapter weights for a subject, as used by paper blueprints. */
export function defaultChapterWeights(subject: SubjectId): Record<string, number> {
  return Object.fromEntries(SYLLABUS[subject].chapters.map((c) => [c.id, c.weight]));
}

export function chapterName(subject: SubjectId, chapterId: string): string {
  return SYLLABUS[subject].chapters.find((c) => c.id === chapterId)?.name ?? chapterId;
}
