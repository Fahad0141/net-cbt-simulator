import type { SubjectId } from '@/engine/types';

/**
 * Chapter structure of every NET subject (based on the HSSC/FSc Part I & II syllabi
 * that the NET is drawn from). Chapter ids are the contract between the question
 * bank (`src/bank/<subject>/<chapter-id>.ts`) and paper assembly.
 *
 * `weight` is the chapter's relative share of questions in a generated paper. It
 * reflects how often each chapter appears in reported NET papers (see
 * docs/EXAM_PATTERN.md); a paper draws chapter counts proportionally, with a
 * little per-paper jitter, so no two papers have the identical distribution.
 */
export interface ChapterInfo {
  id: string;
  name: string;
  /** FSc part the chapter belongs to (`XI` = Part I, `XII` = Part II). */
  part: 'XI' | 'XII' | '-';
  weight: number;
  /** Key sub-topics, used by authors and the bank browser. */
  topics: readonly string[];
}

export interface SubjectInfo {
  id: SubjectId;
  name: string;
  chapters: readonly ChapterInfo[];
}

const ch = (
  id: string,
  name: string,
  part: ChapterInfo['part'],
  weight: number,
  topics: readonly string[],
): ChapterInfo => ({
  id,
  name,
  part,
  weight,
  topics,
});

